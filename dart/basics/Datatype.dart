void main(){ 
  /* Data type is a clasification or categorization of data in programming. It tell the computer what 
  the programmer intend to do and the type of operation that can be perform on a given data */

  // Numbers Types in Dart(int, double, num, )
  //int
  int age = 969;
  int numberOfPlanets = 8;
  print(age);
  print(numberOfPlanets);

  //double
  double pmsPrice = 1_330.5;
  double accountBalance = 10_000_000.0;
  print(pmsPrice);
  print(accountBalance);

  //num is the umbrellar type for int and double

  num height = 6;
  print(height);

  height = 5.11;
  print(height);

  //String
  String name = "Faith";
  String School = "Sqi";

  print(name);
  print(School);

  //Boolean
  bool isBroke = true;
  bool isTeenager = false;

  print(isBroke);
  print(isTeenager);

  //null
  String? test; 
  print(test);
}



void main() {
  // a. Arithimetic operators(aka math operators)

  int num1 = 8, num2 = 6;

  // Addition
  print("$num1 + $num2 = ${num1 + num2}");
  print(10 + 5);

  // Substraction
  print("$num1 - $num2 = ${num1 - num2}");
  print(10 - 5);

  // Multiplication
  print("$num1 x $num2 = ${num1 * num2}");
  print(10 * 5);

  // Division
  print("$num1 / $num2 = ${num1 / num2}");
  print(10 / 5);

  // interger division
  print("$num1 ~/ $num2 = ${num1 ~/ num2}");
  print(10 ~/ 5);

  // Modulus
  print("$num1 % $num2 = ${num1 % num2}");
  print(10 % 5);

  print("${10 % 2 == 0 ? "Even" : "Odd"}");

  // 2.
}

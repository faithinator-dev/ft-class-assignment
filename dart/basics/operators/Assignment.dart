void main() {
  //Assignment operation
  String username = "faith tolu";
  print(username);

  int age = 40;
  print(age);

  // compound assignment
  age = age + 10;
  print(age);

  age += 50; //Short hand syntax
  print(age);

  // decrement operators
  int x = 5;
  print(--x); //Decrement before printout
  print(x--); // prints out before decreement
  print(x);

  //increment operators
  int y = 10;
  print(++y); // increment before print out
  print(y++); // increments after print out
  print(y);
}
